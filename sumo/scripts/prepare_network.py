#!/usr/bin/env python3
"""Prepare a SUMO work directory from an OSM bbox or local OSM XML file.

Requires SUMO tools on PATH (netconvert). Inside Docker:
  SUMO_HOME is typically /usr/share/sumo
  Work outputs go to SUMO_WORK_DIR (default /tmp/cyclegen-sumo)

Examples:
  python3 prepare_network.py --bbox 48.78,1.58,48.84,1.66 --work-dir /tmp/cyclegen-sumo
  python3 prepare_network.py --osm-file /data/map.osm.xml --work-dir /tmp/cyclegen-sumo
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

DEFAULT_OVERPASS = os.environ.get(
    "OVERPASS_URL", "https://overpass-api.de/api/interpreter"
)
DEFAULT_WORK_DIR = os.environ.get("SUMO_WORK_DIR", "/tmp/cyclegen-sumo")
DEFAULT_TEMPLATES = Path(os.environ.get("SUMO_TEMPLATES", "/sumo/templates"))

# Ego vType stubs (Eco / Normal / Agressif) — mirror sumo/templates/vtypes.add.xml
VALID_VTYPES = frozenset({"Eco", "Normal", "Agressif", "Sportif"})


def write_routes(
    work_dir: Path,
    *,
    edges: str | list[str] = "",
    vtype: str = "Normal",
    route_id: str = "ego_route",
    vehicle_id: str = "ego",
) -> Path:
    """Write routes.rou.xml with ego route edges and driving-style vType.

    Used by the CLI stub and by SumoBridge after network generation.
    """
    if vtype not in VALID_VTYPES:
        raise ValueError(f"vtype must be one of {sorted(VALID_VTYPES)}, got {vtype!r}")
    edge_str = edges if isinstance(edges, str) else " ".join(edges)
    content = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- Generated by prepare_network.write_routes — ego edges + vType -->\n"
        "<routes>\n"
        f'    <route id="{route_id}" edges="{edge_str}"/>\n'
        f'    <vehicle id="{vehicle_id}" type="{vtype}" route="{route_id}" '
        'depart="0" departLane="best" departSpeed="max"/>\n'
        "</routes>\n"
    )
    out = Path(work_dir) / "routes.rou.xml"
    out.write_text(content, encoding="utf-8")
    print(f"[prepare_network] routes → {out} (type={vtype}, edges={edge_str!r})", flush=True)
    return out


def find_sumo_binary() -> str | None:
    """Locate sumo / sumo-gui using SUMO_BINARY, PATH, or SUMO_HOME/bin."""
    preferred = os.environ.get("SUMO_BINARY", "sumo")
    found = shutil.which(preferred)
    if found:
        return found
    if preferred != "sumo":
        found = shutil.which("sumo")
        if found:
            return found
    sumo_home = os.environ.get("SUMO_HOME")
    if sumo_home:
        for name in (preferred, "sumo", "sumo-gui"):
            candidate = Path(sumo_home) / "bin" / name
            if candidate.is_file() and os.access(candidate, os.X_OK):
                return str(candidate)
    return None


def _parse_bbox(raw: str) -> tuple[float, float, float, float]:
    parts = [p.strip() for p in raw.split(",")]
    if len(parts) != 4:
        raise argparse.ArgumentTypeError(
            "bbox must be south,west,north,east (4 comma-separated floats)"
        )
    try:
        south, west, north, east = (float(p) for p in parts)
    except ValueError as exc:
        raise argparse.ArgumentTypeError(f"invalid bbox floats: {raw}") from exc
    if not (south < north and west < east):
        raise argparse.ArgumentTypeError(
            "bbox requires south < north and west < east"
        )
    return south, west, north, east


def _overpass_query(south: float, west: float, north: float, east: float) -> str:
    # Highway ways + their nodes — enough for netconvert passenger network
    return f"""[out:xml][timeout:180];
(
  way["highway"]({south},{west},{north},{east});
  node(w);
);
out body;
"""


def download_osm_overpass(
    bbox: tuple[float, float, float, float],
    dest: Path,
    overpass_url: str = DEFAULT_OVERPASS,
) -> Path:
    south, west, north, east = bbox
    query = _overpass_query(south, west, north, east)
    print(f"[prepare_network] Overpass download → {dest}", flush=True)
    # Overpass expects form field `data=<query>` and a non-empty User-Agent.
    payload = urllib.parse.urlencode({"data": query}).encode("utf-8")
    req = urllib.request.Request(
        overpass_url,
        data=payload,
        headers={
            "Content-Type": "application/x-www-form-urlencoded",
            "Accept": "application/osm3s+xml, application/xml, text/xml, */*",
            "User-Agent": "CycleGen/0.1 (prepare_network; research)",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=240) as resp:
            body = resp.read()
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")[:500]
        raise RuntimeError(
            f"Overpass HTTP {exc.code} ({overpass_url}): {exc.reason}. {detail}"
        ) from exc
    except urllib.error.URLError as exc:
        raise RuntimeError(
            f"Overpass download failed ({overpass_url}): {exc}"
        ) from exc
    if b"<osm" not in body[:2000] and b"<?xml" not in body[:200]:
        raise RuntimeError(
            f"Overpass response does not look like OSM XML ({len(body)} bytes); "
            "check bbox / API limits"
        )
    if len(body) < 200:
        raise RuntimeError(
            f"Overpass returned suspiciously small payload ({len(body)} bytes); "
            "check bbox / API limits"
        )
    dest.write_bytes(body)
    print(f"[prepare_network] wrote {dest} ({len(body)} bytes)", flush=True)
    return dest


def find_netconvert() -> str | None:
    """Locate netconvert using PATH and optional SUMO_HOME."""
    found = shutil.which("netconvert")
    if found:
        return found
    sumo_home = os.environ.get("SUMO_HOME")
    if sumo_home:
        candidate = Path(sumo_home) / "bin" / "netconvert"
        if candidate.is_file() and os.access(candidate, os.X_OK):
            return str(candidate)
    return None


def run_netconvert(osm_file: Path, net_out: Path) -> None:
    """Invoke netconvert to build network.net.xml.

    SUMO_HOME must point at the SUMO install root (e.g. /usr/share/sumo on Ubuntu
    packages, or a local build). netconvert must be on PATH or under $SUMO_HOME/bin.
    """
    netconvert = find_netconvert()
    if not netconvert:
        sumo_home = os.environ.get("SUMO_HOME", "<unset>")
        raise RuntimeError(
            "netconvert not found. Install SUMO (sumo + sumo-tools) or use the "
            "Docker image (`docker compose build sumo` / `docker compose run --rm sumo ...`).\n"
            f"  SUMO_HOME={sumo_home}\n"
            "  Hint: on Debian/Ubuntu packages, SUMO_HOME=/usr/share/sumo"
        )

    cmd = [
        netconvert,
        "--osm-files",
        str(osm_file),
        "--output-file",
        str(net_out),
        "--geometry.remove",
        "true",
        "--remove-edges.isolated",
        "true",
        "--keep-edges.by-vclass",
        "passenger",
        "--no-turn-restrictions",
        "false",
        "--tls.guess",
        "true",
        "--tls.discard-simple",
        "true",
    ]
    print(f"[prepare_network] running: {' '.join(cmd)}", flush=True)
    try:
        result = subprocess.run(
            cmd,
            check=False,
            capture_output=True,
            text=True,
        )
    except OSError as exc:
        raise RuntimeError(f"failed to execute netconvert: {exc}") from exc

    if result.returncode != 0:
        err = (result.stderr or result.stdout or "").strip()
        raise RuntimeError(
            f"netconvert exited {result.returncode}\n{err}"
        )
    if not net_out.is_file():
        raise RuntimeError(f"netconvert succeeded but {net_out} missing")
    print(f"[prepare_network] network → {net_out}", flush=True)


def copy_templates(templates_dir: Path, work_dir: Path) -> None:
    mapping = {
        "cyclegen.sumocfg": "cyclegen.sumocfg",
        "vtypes.add.xml": "vtypes.add.xml",
    }
    for src_name, dst_name in mapping.items():
        src = templates_dir / src_name
        dst = work_dir / dst_name
        if not src.is_file():
            print(
                f"[prepare_network] WARN: template missing {src}, skipping",
                flush=True,
            )
            continue
        shutil.copy2(src, dst)
        print(f"[prepare_network] copied {src.name} → {dst}", flush=True)


def write_routes_stub(work_dir: Path, *, vtype: str = "Normal") -> Path:
    """Write an empty-edge routes stub (edges filled later by SumoBridge)."""
    return write_routes(work_dir, edges="", vtype=vtype)


def prepare_network(
    *,
    bbox: tuple[float, float, float, float] | None = None,
    osm_file: Path | None = None,
    work_dir: Path | None = None,
    templates_dir: Path | None = None,
    overpass_url: str = DEFAULT_OVERPASS,
    skip_netconvert: bool = False,
) -> Path:
    """Build work_dir with OSM → network.net.xml + routes + sumocfg + vtypes.

    Returns the work directory path.
    """
    if (bbox is None) == (osm_file is None):
        raise ValueError("provide exactly one of bbox or osm_file")

    work = Path(work_dir or DEFAULT_WORK_DIR)
    work.mkdir(parents=True, exist_ok=True)
    templates = Path(templates_dir or DEFAULT_TEMPLATES)

    if osm_file is not None:
        src = Path(osm_file)
        if not src.is_file():
            raise FileNotFoundError(f"OSM file not found: {src}")
        osm_dest = work / "map.osm.xml"
        if src.resolve() != osm_dest.resolve():
            shutil.copy2(src, osm_dest)
        print(f"[prepare_network] using OSM file {osm_dest}", flush=True)
    else:
        assert bbox is not None
        osm_dest = work / "map.osm.xml"
        download_osm_overpass(bbox, osm_dest, overpass_url=overpass_url)

    net_out = work / "network.net.xml"
    if skip_netconvert:
        print("[prepare_network] skip_netconvert: leaving network.net.xml untouched", flush=True)
    else:
        run_netconvert(osm_dest, net_out)

    write_routes_stub(work)
    copy_templates(templates, work)

    print(f"[prepare_network] ready: {work}", flush=True)
    return work


def build_arg_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Download/convert OSM into a CycleGen SUMO work directory",
    )
    src = p.add_mutually_exclusive_group(required=True)
    src.add_argument(
        "--bbox",
        type=_parse_bbox,
        metavar="S,W,N,E",
        help="Bounding box south,west,north,east (WGS84)",
    )
    src.add_argument(
        "--osm-file",
        type=Path,
        help="Existing OSM XML file (skip Overpass download)",
    )
    p.add_argument(
        "--work-dir",
        type=Path,
        default=Path(DEFAULT_WORK_DIR),
        help=f"Output directory (default: {DEFAULT_WORK_DIR})",
    )
    p.add_argument(
        "--templates-dir",
        type=Path,
        default=DEFAULT_TEMPLATES,
        help=f"SUMO templates directory (default: {DEFAULT_TEMPLATES})",
    )
    p.add_argument(
        "--overpass-url",
        default=DEFAULT_OVERPASS,
        help="Overpass interpreter URL",
    )
    p.add_argument(
        "--skip-netconvert",
        action="store_true",
        help="Only download/copy OSM + write stubs (no netconvert)",
    )
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_arg_parser().parse_args(argv)
    try:
        prepare_network(
            bbox=args.bbox,
            osm_file=args.osm_file,
            work_dir=args.work_dir,
            templates_dir=args.templates_dir,
            overpass_url=args.overpass_url,
            skip_netconvert=args.skip_netconvert,
        )
    except Exception as exc:  # noqa: BLE001 — CLI surface
        print(f"[prepare_network] ERROR: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
